# ==============================================================================
# 3. GB/T 4754-1994 / 2002 / 2011 / 2017 之间的微调
# ==============================================================================
# 1994-2017 各版本30 个二位数对应关系:
# - 1994 → 2002: 仅替换尾号, 主类未变
# - 2002 → 2011: 编号体系从字母改为数字, 但 2 位数代码核心类集合一致
# - 2011 → 2017: 极少数调整 (如 "汽车制造" 与 "铁路船舶" 内部结构调整, 但 2 位数编码一致)
#
# 实践处理: 1994 之后的代码基本 1:1, 只需替换 1994(字母) ↔ 2011(数字)
GB_1994_ALPHA_TO_2011 = {
    '13': '13', '14': '14', '15': '15', '16': '16',
    '17': '17', '18': '18', '19': '19', '20': '20',
    '21': '21', '22': '22', '23': '23', '24': '24',
    '25': '25', '26': '26', '27': '27', '28': '28',
    '29': '29', '30': '30', '31': '31', '32': '32',
    '33': '33', '34': '34', '35': '35', '36': '36',
    '37': '37', '38': '38', '39': '39', '40': '40',
    '41': '41', '42': '42',
    # 注: 1994 在 41 后还有 90-91 (工艺美术), 现并入 24 / 41
    '90': '24',  # 工艺美术品 → 文教用品
    '91': '41',  # 其他制造业 (保留)
}


# ==============================================================================
# 4. 实操映射函数 (供 B-1 清洗流程调用)
# ==============================================================================
def unified_code_for_1984(code84):
    """GB/T 4754-1984 三位数 → 30 类统一编码"""
    if code84 in GB1984_TO_UNIFIED:
        return GB1984_TO_UNIFIED[code84]
    # 模糊匹配: 取前两位
    code2 = code84[:2] if len(code84) >= 2 else code84
    return (code2, 1.0)


def unified_code_for_1994(code94):
    """GB/T 4754-1994 二位数 → 2011 二位数 (直接对应)"""
    if code94 in GB_1994_ALPHA_TO_2011:
        return GB_1994_ALPHA_TO_2011[code94]
    return code94


def unified_code_for_2011(code11):
    """GB/T 4754-2011 / 2017 二位数 → 直接是 30 类"""
    if code11 in [c[0] for c in UNIFIED_30]:
        return code11
    return None


