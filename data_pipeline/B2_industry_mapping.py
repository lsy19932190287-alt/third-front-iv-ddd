# 5. 输出 LaTeX 映射表
# ==============================================================================
def make_mapping_long_table():
    """输出 mapping_long.csv 给下游清洗使用"""
    rows = []
    for code84, (unif, w) in GB1984_TO_UNIFIED.items():
        rows.append({
            'source_period': '1984 (二普工业)',
            'source_code': code84,
            'unified_code': unif,
            'weight': w,
            'note': '基于主营业务内容匹配',
        })
    for c94, c11 in GB_1994_ALPHA_TO_2011.items():
        rows.append({
            'source_period': '1994 (三普)',
            'source_code': c94,
            'unified_code': c11,
            'weight': 1.0,
            'note': '字母编码到数字编码直转',
        })
    df = pd.DataFrame(rows)
    return df


def make_sector_summary_table():
    """输出 30 个统一二位数制造业大类的 LaTeX 表"""
    lines = []
    lines.append(r"\begin{table}[htbp]")
    lines.append(r"\centering")
    lines.append(r"\small")
    lines.append(r"\caption{Unified 30 Manufacturing Sectors --- 三线建设主样本分类标准 "
                  r"GB/T 4754-2011}")
    lines.append(r"\label{tab:unified_sectors}")
    lines.append(r"\begin{tabular}{c l l}")
    lines.append(r"\toprule")
    lines.append(r"Code & 中文名 & English Name \\")
    lines.append(r"\midrule")
    for code, cn, en, _ in UNIFIED_30:
        lines.append(f"{code} & {cn} & \\textit{{{en}}} \\\\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\begin{flushleft}\footnotesize")
    lines.append(r"\textit{Notes:} 跨期版本 GB/T 4754-1984$\to$2011 的映射权重经作者手工核对, "
                 r"1984 三位数代码与 2011 二位数代码基数大部分对齐 (估算 overlap $>85\%$). "
                 r"采掘业 (B类, 06-12) 与公用事业 (D类, 44-46) 不计入本研究主样本.")
    lines.append(r"\end{flushleft}")
    lines.append(r"\end{table}")
    return '\n'.join(lines)


def make_mapping_long_tex():
    """输出 1984 → 30 类映射长表 (用于论文附录 B.1.1)"""
    by_unified = {}
    for code84, (unif, w) in GB1984_TO_UNIFIED.items():
        by_unified.setdefault(unif, []).append((code84, w))

    lines = []
    lines.append(r"\begin{table}[htbp]")
    lines.append(r"\centering")
    lines.append(r"\footnotesize")
    lines.append(r"\caption{Crosswalk: GB/T 4754-1984 $\to$ Unified 30 Sectors "
                  r"(三线建设 Exit-DDD 主样本, $\sim$110 个 1984 三位数代码)}")
    lines.append(r"\label{tab:crosswalk_1984}")
    lines.append(r"\begin{tabular}{l c l l}")
    lines.append(r"\toprule")
    lines.append(r"Unified (2011) & Code & 1984 三位数类 (节选) & Mapping \\")
    lines.append(r"\midrule")
    for code, cn, en, _ in UNIFIED_30:
        if code in by_unified:
            items = by_unified[code]
            n_items = len(items)
            items_str = ', '.join([f"\\texttt{{{c}}}" for c, _ in items[:5]])
            if n_items > 5:
                items_str += f" ... (共 {n_items} 个)"
            avg_w = np.mean([w for _, w in items])
            mapping_note = 'exact' if all(w == 1.0 for _, w in items) else f"weighted ($\\bar w = {avg_w:.2f}$)"
            lines.append(f"\\textbf{{{code}}} {cn[:8]} & {code} & {items_str} & {mapping_note} \\\\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    return '\n'.join(lines)


