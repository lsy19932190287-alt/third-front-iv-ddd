# 5. 输出汇总文件
# ==============================================================================
def make_anchoring_summary_tex():
    """输出 LaTeX 政策说明 + 县计数表"""
    n_main, _ = count_main_districts()
    n_post1997, _ = count_districts_after_1997_strip()

    lines = []
    lines.append(r"\begin{table}[htbp]")
    lines.append(r"\centering")
    lines.append(r"\small")
    lines.append(r"\caption{§B-1 行政区划锚定 --- 三线建设县样本框架}")
