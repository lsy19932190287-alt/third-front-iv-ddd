ANCHORING_STRATEGY = """
============================================================
§B-1 区划锚定 — 操作方案 (用户策略对)
============================================================

【Strategy 1: 推荐主样本 (Hard Anchor at 1985)】
  · 用 1985 年第二次工业普查的县级边界作为分析单元
  · 三线建设"~210 县" = 1985 标准下 四川(140) + 贵州(75) ≈ 215 县
  · 重庆 1997 直辖划走 ~30 县, 在 Hard Anchor 下保留"包含"(历史归属不变)
  · 注: 行政划动不影响企业生产函数 → 不构成 DID 识别 bias

【Strategy 2: 稳健性 — Soft Tracking (Apply 2010 边界)】
  1) 1997 重庆剥离: 原属川东的 30+ 县从"四川"划归"重庆"
  2) 2010+ 撤县设区: 若某县并入地级市辖区, 该县所有企业归并该区

【Strategy 3: 中间版 — 1997 边界快照】
  仅适用 1997 重庆直辖剥离事件. 1997 后重庆单独处理.

【我们在主样本的选择】
  · Main: 1985 Hard Anchor (Strategy 1) — "川黔一锅端"
  · Robustness: 1997 边界 + 2010 边界 (Strategy 2 + Strategy 3)
  · 附录 Table A3: 报告不同边界下的系数稳健性
============================================================
"""


# ==============================================================================
# 4. 县列表生成 + 计数验证 (在主样本中正确扣除重庆剥离部分)
# ==============================================================================
def list_all_districts(d):
    """递归列出所有县级名"""
    out = []
    for k, v in d.items():
        if isinstance(v, dict):
            out.extend(list_all_districts(v))
        elif isinstance(v, list):
            out.extend(v)
    return out


def count_main_districts():
    """1985 锚定 (含 1997 重庆剥离前) — 共 249 县"""
    all_list_1985 = list_all_districts(DISTRICTS_1985)
    return len(all_list_1985), all_list_1985


def count_districts_after_1997_strip():
    """剥离重庆 30 县 + 重复的黔江(3县), 净剥离 36 县, 主样本剩 213 县"""
    districts = list_all_districts(DISTRICTS_1985)
    # 去重
    districts = list(set(districts))
    # 剥离重庆
    stripped = set()
    for region, counties in CHONGQING_STRIPPED_1985.items():
        stripped.update(counties)
    # 贵州黔江已在 CHONGQING_STRIPPED_1985 中, 已剥离
    main = [d for d in districts if d not in stripped]
    return len(main), main


